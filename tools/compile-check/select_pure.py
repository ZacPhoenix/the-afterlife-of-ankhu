#!/usr/bin/env python3
"""Pick the engine-free .cs files for Ankhu.Tests.Pure and write PureFiles.g.props.

usage: select_pure.py ASSETS_ANKHU_DIR OUT_PROPS [EXCLUDED_LIST]
A file is a candidate when it lives under Runtime/ (outside Integration/, which is always compiled)
or Tests/EditMode/ and never mentions UnityEngine/UnityEditor/InputSystem. EXCLUDED_LIST holds
repo-relative paths that failed to compile in an earlier pass (they depend on Unity-bound code).
Prints the number of selected test files.
"""
import os
import re
import sys
from xml.sax.saxutils import escape

UNITY = re.compile(r"\bUnity(Engine|Editor)\b|\bInputSystem\b|\bTMPro\b|\bMonoBehaviour\b|\bScriptableObject\b")


def main(root, out, excluded_path=None):
    excluded = set()
    if excluded_path and os.path.exists(excluded_path):
        excluded = {l.strip() for l in open(excluded_path) if l.strip()}
    picked, tests = [], 0
    for sub in ("Runtime", os.path.join("Tests", "EditMode")):
        base = os.path.join(root, sub)
        for dp, dn, fn in os.walk(base):
            dn.sort()
            if os.path.abspath(dp).startswith(os.path.abspath(os.path.join(root, "Runtime", "Integration"))):
                continue
            for f in sorted(fn):
                if not f.endswith(".cs"):
                    continue
                p = os.path.abspath(os.path.join(dp, f))
                if p in excluded:
                    continue
                try:
                    src = open(p, encoding="utf-8-sig", errors="replace").read()
                except OSError:
                    continue
                if UNITY.search(src):
                    continue
                picked.append(p)
                if sub.startswith("Tests") and re.search(r"\[\s*(Test|TestCase|TestCaseSource)\b", src):
                    tests += 1
    with open(out, "w") as fh:
        fh.write("<Project>\n  <!-- generated by compile-check.sh; do not edit -->\n  <ItemGroup>\n")
        for p in picked:
            fh.write(f'    <Compile Include="{escape(p)}" />\n')
        fh.write("  </ItemGroup>\n</Project>\n")
    print(tests)


if __name__ == "__main__":
    main(*sys.argv[1:])
