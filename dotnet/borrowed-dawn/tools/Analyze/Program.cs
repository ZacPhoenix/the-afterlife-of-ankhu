using System;
using System.Collections.Generic;
using System.Diagnostics;
using System.IO;
using System.Linq;
using System.Text;
using System.Threading.Tasks;
using Ankhu.BorrowedDawn;
using Ankhu.BorrowedDawn.Analysis;

namespace Ankhu.BorrowedDawn.Tools
{
    /// <summary>
    /// Exhaustive design analysis of the Borrowed Dawn room. Prints a Markdown report.
    /// Usage: dotnet run -c Release -- [output.md]
    /// </summary>
    internal static class Program
    {
        private static readonly string[] CanonicalSolution =
        {
            "flow west", "board elevator", "flow east", "enter gallery", "read inscription",
            "bind elevator", "flow west", "take mirror", "descend to floor", "install mirror",
            "bind shadow", "wake bearer", "flow east", "release elevator", "flow west",
            "board elevator", "flow east", "enter gallery", "go to landing", "recall bell",
            "strike bell", "echo bell", "bind bridge", "cross bridge", "he who returns the morning",
        };

        private static readonly string[] GreyboxSolution =
        {
            "flow west", "board elevator", "flow east", "bind elevator", "flow west",
            "take mirror", "go to gallery", "flow east", "release elevator", "read inscription",
            "lower ladder", "descend", "install mirror", "bind shadow", "wake bearer",
            "go to gallery", "go to landing", "bind bridge", "recall bell", "strike bell",
            "echo bell", "go to bridge", "go to gate", "he who returns the morning",
        };

        private sealed class Variant
        {
            public string Question;
            public Func<RoomState, Command, bool> AllowCommand = (s, c) => true;
            public Func<RoomState, bool> AllowState;
            public IReadOnlyList<Command> Result;
        }

        private static int Main(string[] args)
        {
            if (args.Length > 0 && args[0] == "--teaching") return Teaching.Run(args.Length > 1 ? args[1] : null);

            RuleProfile profile = RuleProfile.Prototype;
            var rest = new List<string>();
            for (int i = 0; i < args.Length; i++)
            {
                if (args[i] == "--profile" && i + 1 < args.Length) profile = (RuleProfile)Enum.Parse(typeof(RuleProfile), args[++i], true);
                else rest.Add(args[i]);
            }
            args = rest.ToArray();
            string[] canonical = profile == RuleProfile.Greybox ? GreyboxSolution : CanonicalSolution;

            var sw = Stopwatch.StartNew();
            StateSpace space = StateSpace.Explore(profile: profile);
            double exploreMs = sw.Elapsed.TotalMilliseconds;

            var md = new StringBuilder();
            md.AppendLine($"# Borrowed Dawn: reachable state analysis ({profile} rules)");
            md.AppendLine();
            md.AppendLine("Generated by tools/Analyze from the Ankhu.BorrowedDawn rules. Undo and reset are excluded from the search, so a softlock means the gate can no longer be opened by play alone.");
            md.AppendLine();

            // ------------------------------------------------------------ graph summary
            int won = space.States.Values.Count(s => s.Won);
            var softlocks = space.Softlocks.ToList();
            var deadEnds = space.DeadEnds.ToList();
            var solution = space.ShortestSolution();
            long shortestCount = space.CountShortestSolutions();
            var worst = space.DistanceToGoal.OrderByDescending(kv => kv.Value).First();

            md.AppendLine("## Graph summary");
            md.AppendLine();
            md.AppendLine("| Measure | Value |");
            md.AppendLine("|---|---|");
            md.AppendLine($"| Reachable states | {space.States.Count} |");
            md.AppendLine($"| Accepted transitions | {space.Edges.Count} |");
            md.AppendLine($"| Won states | {won} |");
            md.AppendLine($"| Softlocked states | {softlocks.Count} |");
            md.AppendLine($"| States with no accepted command (excluding won) | {deadEnds.Count} |");
            md.AppendLine($"| Shortest solution length | {solution?.Count.ToString() ?? "none"} |");
            md.AppendLine($"| Distinct shortest solutions | {shortestCount} |");
            md.AppendLine($"| Authored solution length | {canonical.Length} |");
            md.AppendLine($"| Worst case remaining distance from any reachable state | {worst.Value} |");
            md.AppendLine($"| Exploration time | {exploreMs:F1} ms |");
            md.AppendLine();

            // ------------------------------------------------------------ canonical replay
            md.AppendLine("## Authored solution replay");
            md.AppendLine();
            var session = new PuzzleSession(profile);
            bool canonicalOk = true;
            for (int i = 0; i < canonical.Length; i++)
            {
                var r = session.Submit(canonical[i]);
                if (!r.Accepted)
                {
                    canonicalOk = false;
                    md.AppendLine($"Step {i + 1} \"{canonical[i]}\" was rejected: {r.Message}");
                    break;
                }
            }
            md.AppendLine(canonicalOk && session.State.Won
                ? $"All {canonical.Length} typed steps accepted. Final state is won."
                : "Canonical replay FAILED.");
            md.AppendLine();

            // ------------------------------------------------------------ shortest solution
            md.AppendLine("## One shortest solution");
            md.AppendLine();
            if (solution != null)
            {
                for (int i = 0; i < solution.Count; i++) md.AppendLine($"{i + 1}. {solution[i]}");
            }
            md.AppendLine();

            // ------------------------------------------------------------ worst state
            md.AppendLine("## Furthest recoverable state");
            md.AppendLine();
            md.AppendLine($"`{space.States[worst.Key]}` needs {worst.Value} commands to finish.");
            md.AppendLine();

            if (softlocks.Count > 0)
            {
                md.AppendLine("## Softlocks");
                md.AppendLine();
                foreach (var s in softlocks.Take(50)) md.AppendLine($"- `{s}` reached by: {string.Join(", ", space.PathTo(s.Pack()))}");
                md.AppendLine();
            }

            // ------------------------------------------------------------ design questions
            bool ElevatorBind(Command c) => c.Kind == CommandKind.Bind && c.Target == BindTarget.Elevator;
            bool IsFloorAction(Command c) => c.Kind == CommandKind.WakeBearer || c.Kind == CommandKind.SleepBearer || (c.Kind == CommandKind.Bind && c.Target == BindTarget.Shadow);
            bool UpperLocation(Location l) => l == Location.Gallery || l == Location.Landing || l == Location.Lift;

            var variants = new List<Variant>
            {
                new Variant
                {
                    Question = "Solvable without ever binding the elevator?",
                    AllowCommand = (s, c) => !ElevatorBind(c),
                },
                new Variant
                {
                    Question = "Solvable without ever holding two bindings at once except shadow plus bridge?",
                    AllowState = s => s.BindingCount < 2 || s.Bindings == (BindingSet.Shadow | BindingSet.Bridge),
                },
                new Variant
                {
                    Question = "Solvable if the elevator binding must be gone before the mirror is installed?",
                    AllowState = s => !(s.Mirror == MirrorPlace.Socket && s.IsBound(BindTarget.Elevator)),
                },
                new Variant
                {
                    Question = "Solvable if the elevator is only ever released while water is east (the help text's \"physically support\" step)?",
                    AllowCommand = (s, c) => !(c.Kind == CommandKind.Release && c.Target == BindTarget.Elevator && s.Water == WaterSide.West),
                },
                new Variant
                {
                    Question = "Solvable with the bell sequence (recall, strike, echo) done before the mirror is taken?",
                    AllowState = s => !(s.Mirror != MirrorPlace.Raft && !s.EchoActive),
                },
                new Variant
                {
                    Question = "Solvable if the inscription is only read last, after echo and bridge are both done?",
                    AllowCommand = (s, c) => !(c.Kind == CommandKind.ReadInscription && !(s.EchoActive && s.Mirror == MirrorPlace.Socket)),
                },
                new Variant
                {
                    Question = "Proximity profile A: wake, sleep and bind shadow only from the floor",
                    AllowCommand = (s, c) => !IsFloorAction(c) || s.Location == Location.Floor,
                },
                new Variant
                {
                    Question = "Proximity profile B: profile A, plus echo bell only from the landing or gate",
                    AllowCommand = (s, c) => (!IsFloorAction(c) || s.Location == Location.Floor)
                        && (c.Kind != CommandKind.EchoBell || s.Location == Location.Landing || s.Location == Location.Gate),
                },
                new Variant
                {
                    Question = "Proximity profile C: profile B, plus flow only from the floor or while riding the lift",
                    AllowCommand = (s, c) => (!IsFloorAction(c) || s.Location == Location.Floor)
                        && (c.Kind != CommandKind.EchoBell || s.Location == Location.Landing || s.Location == Location.Gate)
                        && (c.Kind != CommandKind.Flow || s.Location == Location.Floor || s.Location == Location.Lift),
                },
                new Variant
                {
                    Question = "Proximity profile D: profile C, plus release elevator only from an upper location",
                    AllowCommand = (s, c) => (!IsFloorAction(c) || s.Location == Location.Floor)
                        && (c.Kind != CommandKind.EchoBell || s.Location == Location.Landing || s.Location == Location.Gate)
                        && (c.Kind != CommandKind.Flow || s.Location == Location.Floor || s.Location == Location.Lift)
                        && !(c.Kind == CommandKind.Release && c.Target == BindTarget.Elevator && !UpperLocation(s.Location)),
                },
            };

            // Independent searches. Cheap, but run them across cores as requested.
            Parallel.ForEach(variants, v => v.Result = StateSpace.ShortestSolutionWhere(v.AllowCommand, v.AllowState, profile: profile));

            md.AppendLine("## Design questions");
            md.AppendLine();
            md.AppendLine("| Question | Answer | Shortest length |");
            md.AppendLine("|---|---|---|");
            foreach (var v in variants)
            {
                md.AppendLine($"| {v.Question} | {(v.Result != null ? "Yes" : "No")} | {(v.Result != null ? v.Result.Count.ToString() : "n/a")} |");
            }
            md.AppendLine();
            foreach (var v in variants.Where(v => v.Result != null))
            {
                md.AppendLine($"**{v.Question}**");
                md.AppendLine();
                md.AppendLine(string.Join(" > ", v.Result.Select(c => c.ToString())));
                md.AppendLine();
            }

            // ------------------------------------------------------------ elevator binding timing
            md.AppendLine("## Elevator binding window");
            md.AppendLine();
            var mirrorReachable = space.States.Values.Where(s => s.Mirror != MirrorPlace.Raft).ToList();
            bool everTakenUnbound = space.Edges.Any(e => e.Command.Kind == CommandKind.TakeMirror && !space.States[e.From].IsBound(BindTarget.Elevator));
            md.AppendLine($"- Mirror ever taken without the elevator bound: {(everTakenUnbound ? "yes" : "no")}.");
            var releaseWhileCarried = space.Edges.Any(e => e.Command.Kind == CommandKind.Release && e.Command.Target == BindTarget.Elevator && space.States[e.From].Mirror == MirrorPlace.Carried
                && space.DistanceToGoal.ContainsKey(e.To));
            md.AppendLine($"- Elevator can be released while the mirror is still carried, and the room remains solvable: {(releaseWhileCarried ? "yes" : "no")}.");
            md.AppendLine();

            // ------------------------------------------------------------ feedback frequency
            md.AppendLine("## Rejection outcomes across all reachable (state, command) pairs");
            md.AppendLine();
            var outcomeCounts = new Dictionary<Outcome, int>();
            foreach (var s in space.States.Values)
            {
                foreach (var c in RoomRules.AllCommands)
                {
                    var o = RoomRules.Apply(s, c, profile).Outcome;
                    outcomeCounts[o] = outcomeCounts.TryGetValue(o, out int n) ? n + 1 : 1;
                }
            }
            md.AppendLine("| Outcome | Count |");
            md.AppendLine("|---|---|");
            foreach (var kv in outcomeCounts.OrderByDescending(k => k.Value)) md.AppendLine($"| {kv.Key} | {kv.Value} |");
            md.AppendLine();

            // ------------------------------------------------------------ location independence
            md.AppendLine("## Commands accepted from every location");
            md.AppendLine();
            md.AppendLine("Commands below are accepted somewhere in the reachable space from each listed location. A walking port must decide proximity for these deliberately.");
            md.AppendLine();
            md.AppendLine("| Command | Locations where it is ever accepted |");
            md.AppendLine("|---|---|");
            foreach (var c in RoomRules.AllCommands.Where(c => c.Kind != CommandKind.MoveTo && c.Kind != CommandKind.CrossBridge))
            {
                var locs = space.Edges.Where(e => e.Command.Equals(c)).Select(e => space.States[e.From].Location).Distinct().OrderBy(l => l).ToList();
                md.AppendLine($"| {c} | {string.Join(", ", locs)} |");
            }
            md.AppendLine();

            string report = md.ToString();
            if (args.Length > 0)
            {
                File.WriteAllText(args[0], report);
            }
            Console.Write(report);
            return softlocks.Count == 0 && canonicalOk && solution != null ? 0 : 1;
        }
    }
}
