using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using Ankhu.BorrowedDawn;
using Ankhu.BorrowedDawn.Analysis;

namespace Ankhu.BorrowedDawn.Tools
{
    /// <summary>Solver report for the Anpu teaching rooms. Usage: dotnet run -- --teaching [output.md]</summary>
    internal static class Teaching
    {
        private sealed class LessonCheck
        {
            public string Question;
            public Func<RoomState, Command, bool> Allow;
            public bool ExpectSolvable;
        }

        public static int Run(string outPath)
        {
            var checks = new Dictionary<string, LessonCheck[]>
            {
                [TeachingRooms.Cistern.Id] = new[]
                {
                    new LessonCheck { Question = "Solvable without speaking flow?", Allow = (s, c) => c.Kind != CommandKind.Flow, ExpectSolvable = false },
                },
                [TeachingRooms.HeldStep.Id] = new[]
                {
                    new LessonCheck { Question = "Solvable without binding the elevator?", Allow = (s, c) => c.Kind != CommandKind.Bind, ExpectSolvable = false },
                    new LessonCheck { Question = "Solvable without releasing the elevator?", Allow = (s, c) => c.Kind != CommandKind.Release, ExpectSolvable = false },
                    new LessonCheck { Question = "Solvable without returning the water east after binding?", Allow = (s, c) => !(c.Kind == CommandKind.Flow && c.Direction == WaterSide.East && s.IsBound(BindTarget.Elevator)), ExpectSolvable = false },
                },
                [TeachingRooms.LingeringShadow.Id] = new[]
                {
                    new LessonCheck { Question = "Solvable without binding the shadow?", Allow = (s, c) => !(c.Kind == CommandKind.Bind && c.Target == BindTarget.Shadow), ExpectSolvable = false },
                    new LessonCheck { Question = "Solvable without releasing a thread first (binding limit)?", Allow = (s, c) => c.Kind != CommandKind.Release, ExpectSolvable = false },
                    new LessonCheck { Question = "Solvable without waking the Bearer?", Allow = (s, c) => c.Kind != CommandKind.WakeBearer, ExpectSolvable = false },
                },
            };

            var md = new StringBuilder();
            md.AppendLine("# Anpu teaching rooms: solver report");
            md.AppendLine();
            md.AppendLine("Generated by `tools/Analyze --teaching`. Each room uses the Greybox rules with a restricted vocabulary and its own goal. Undo and reset are excluded.");
            md.AppendLine();
            md.AppendLine("| Room | States | Softlocks | Dead ends | Shortest | Distinct shortest | Worst-case recovery | Lessons enforced |");
            md.AppendLine("|---|---|---|---|---|---|---|---|");

            bool allOk = true;
            var detail = new StringBuilder();
            foreach (RoomDefinition room in TeachingRooms.Sequence.Take(3))
            {
                StateSpace space = StateSpace.Explore(room);
                var softlocks = space.Softlocks.ToList();
                var dead = space.DeadEnds.ToList();
                var path = space.ShortestSolution();
                int worst = space.DistanceToGoal.Values.DefaultIfEmpty(-1).Max();
                bool lessonsOk = true;

                detail.AppendLine($"## {room.Title}");
                detail.AppendLine();
                detail.AppendLine($"Lesson: {room.Lesson}");
                detail.AppendLine();
                detail.AppendLine("Anpu:");
                detail.AppendLine();
                foreach (string line in room.AnpuIntro) detail.AppendLine($"> {line}");
                detail.AppendLine();
                detail.AppendLine("Shortest solution: " + (path == null ? "none" : string.Join(" > ", path.Select(c => c.ToString()))));
                detail.AppendLine();
                detail.AppendLine("| Lesson check | Expected | Result |");
                detail.AppendLine("|---|---|---|");
                foreach (var check in checks[room.Id])
                {
                    var alt = StateSpace.ShortestSolutionWhere(room, check.Allow);
                    bool solvable = alt != null;
                    if (solvable != check.ExpectSolvable) lessonsOk = false;
                    detail.AppendLine($"| {check.Question} | {(check.ExpectSolvable ? "Yes" : "No")} | {(solvable ? "Yes, " + alt.Count + " steps" : "No")} |");
                }
                detail.AppendLine();

                bool ok = softlocks.Count == 0 && dead.Count == 0 && path != null && lessonsOk;
                allOk &= ok;
                md.AppendLine($"| {room.Title} | {space.States.Count} | {softlocks.Count} | {dead.Count} | {path?.Count.ToString() ?? "none"} | {space.CountShortestSolutions()} | {worst} | {(lessonsOk ? "All" : "NO")} |");
            }
            md.AppendLine();
            md.Append(detail);

            string report = md.ToString();
            if (outPath != null) File.WriteAllText(outPath, report);
            Console.Write(report);
            return allOk ? 0 : 1;
        }
    }
}
